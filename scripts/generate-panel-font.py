#!/usr/bin/env python3
"""Regenerate the committed CAN Scope Panel 16 bitmap subset; builds need no Pillow."""
import argparse
import hashlib
from pathlib import Path
import re
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--font', required=True, type=Path, help='SourceHanSansCN-Regular.otf (SIL OFL 1.1)')
parser.add_argument('--output', type=Path, default=ROOT/'firmware/main/board_ui_font_data.h')
args = parser.parse_args()
source = (ROOT/'firmware/main/board_ui_render.c').read_text()
strings = re.findall(r'"(?:\\.|[^"\\])*"', source)
characters = sorted({char for string in strings for char in string if ord(char) > 127})
font = ImageFont.truetype(str(args.font), 16)
assert font.getname() == ('Source Han Sans CN', 'Regular'), 'Use the documented OFL font to preserve attribution.'
digest = hashlib.sha256(args.font.read_bytes()).hexdigest()
lines = [
    '// Generated by scripts/generate-panel-font.py; do not edit glyph data.',
    '// CAN Scope Panel 16: bitmap subset derived from Source Han Sans CN Regular.',
    '// Copyright 2014-2025 Adobe. Glyph data licensed under SIL OFL 1.1.',
    '// See firmware/fonts/OFL-SourceHanSans.txt and firmware/fonts/README.md.',
    f'// Source font SHA256: {digest}',
    '// Fixed 16x16, Pillow anchor lt, threshold >= 100, fit ink without clipping; rows are MSB-left.',
    '#pragma once', 'static const ui_cn_glyph_t ui_cn_glyphs[] = {'
]
for char in characters:
    image = Image.new('L', (24, 24))
    ImageDraw.Draw(image).text((0, 0), char, font=font, anchor='lt', fill=255)
    image = image.point(lambda value: 255 if value >= 100 else 0)
    box = image.getbbox()
    assert box and box[2]-box[0] <= 16 and box[3]-box[1] <= 16, f'Glyph does not fit: {char}'
    # Some hinted glyphs include a blank top row and a seventeenth ink row.
    # Shift only when necessary; never lose the bottom stroke in a 16px cell.
    dx, dy = max(0, box[2]-16), max(0, box[3]-16)
    fitted = image.crop((dx, dy, dx+16, dy+16))
    assert sum(image.tobytes()) == sum(fitted.tobytes()), f'Clipped glyph: {char}'
    image = fitted
    rows = [sum((1 << (15-x)) for x in range(16) if image.getpixel((x, y)) >= 100) for y in range(16)]
    assert any(rows), f'Missing glyph: {char}'
    lines.append(f'    {{0x{ord(char):04x}, {{{", ".join(f"0x{row:04x}" for row in rows)}}}}}, // {char}')
lines.extend(['};', ''])
args.output.write_text('\n'.join(lines))
print(f'{len(characters)} glyphs, {len(characters)*32} bitmap bytes -> {args.output}')
